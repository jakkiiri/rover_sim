"""Measure which slopes the rover_sim rover can drive on.

    ros2 run rover_planner slope_test --write-world /tmp/ramps.world
    ros2 launch rover_sim rover_desert.launch.py world:=/tmp/ramps.world gui:=false stereo:=false
    ros2 run rover_planner slope_test --output slopes.json

The world has flat ground and one wide ramp per angle. For each angle the
rover is teleported onto the ramp (Gazebo's set_entity_state) and driven with
/cmd_vel at teleop speed:

- climb:   from the flat ground at the foot, straight up 5 m of ramp;
- descend: from high on the ramp, straight down for 3 s, then stop;
- park:    standing on the ramp facing uphill with no command for 5 s
           (creep speed only: the wheel brake at zero speed is proportional);
- across:  driving 3.2 m along the ramp's contour (cross-slope), both sides;
- turn:    turning in place one full turn on the ramp.

Each result records how far the rover slid downhill and whether it tipped.
Pose is the Gazebo ground truth (/ground_truth/odom).
"""

import argparse
import json
import math
import sys
import time

FOOT_X = 3.0              # ramp foot (m)
ROW_SPACING = 9.0         # ramps along +y
RAMP_LENGTH = 9.0
RAMP_WIDTH = 7.0
RAMP_THICKNESS = 0.6
BODY_HEIGHT = 0.345       # base_root above the ground when resting (spawn settles from 0.36)
SPEED = 0.4               # teleop speeds
TURN_RATE = 0.5
FRICTION = 0.8            # same as desert.world's ground; ODE uses the smaller of the two mu

DEFAULT_ANGLES = (10, 15, 20, 25, 30, 35, 40)


def ramp_row_y(index):
    return ROW_SPACING * (index + 1)


def quat_mul(a, b):
    aw, ax, ay, az = a
    bw, bx, by, bz = b
    return (aw * bw - ax * bx - ay * by - az * bz,
            aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw)


def slope_pose(angle_deg, row_y, s, lateral=0.0, yaw=0.0):
    """Rover resting on the ramp: s metres up the slope, yaw relative to uphill.

    Returns (x, y, z), quaternion (w, x, y, z). s < 0 is on the flat before the foot.
    """
    t = math.radians(angle_deg) if s > 0 else 0.0
    x = FOOT_X + s * math.cos(t) - BODY_HEIGHT * math.sin(t)
    z = s * math.sin(t) + BODY_HEIGHT * math.cos(t)
    q_slope = (math.cos(-t / 2), 0.0, math.sin(-t / 2), 0.0)    # nose up when facing +x
    q_yaw = (math.cos(yaw / 2), 0.0, 0.0, math.sin(yaw / 2))
    return (x, row_y + lateral, z), quat_mul(q_slope, q_yaw)


def ramp_sdf(angle_deg, row_y, index):
    t = math.radians(angle_deg)
    # Top face centre is RAMP_LENGTH / 2 up the slope from the foot; box centre is half
    # its thickness below that along the surface normal (-sin t, 0, cos t).
    cx = FOOT_X + RAMP_LENGTH / 2 * math.cos(t) + RAMP_THICKNESS / 2 * math.sin(t)
    cz = RAMP_LENGTH / 2 * math.sin(t) - RAMP_THICKNESS / 2 * math.cos(t)
    size = f'{RAMP_LENGTH} {RAMP_WIDTH} {RAMP_THICKNESS}'
    surface = f'<surface><friction><ode><mu>{FRICTION}</mu><mu2>{FRICTION}</mu2></ode></friction></surface>'
    return f'''
    <model name="ramp_{index}_{angle_deg}deg">
      <static>true</static>
      <pose>{cx:.4f} {row_y:.4f} {cz:.4f} 0 {-t:.6f} 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{size}</size></box></geometry>{surface}</collision>
        <visual name="visual"><geometry><box><size>{size}</size></box></geometry>
          <material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>Gazebo/Wood</name></script></material>
        </visual>
      </link>
    </model>'''


def world_sdf(angles):
    ramps = ''.join(ramp_sdf(a, ramp_row_y(i), i) for i, a in enumerate(angles))
    return f'''<?xml version="1.0"?>
<!-- Generated by rover_planner slope_test --write-world. Angles: {list(angles)} deg. -->
<sdf version="1.6">
  <world name="slope_test">
    <gravity>0 0 -9.81</gravity>
    <physics name="default_physics" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_update_rate>1000</real_time_update_rate>
      <ode><solver><type>quick</type><iters>150</iters><sor>1.0</sor></solver></ode>
    </physics>
    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so">
      <ros><namespace>/gazebo</namespace></ros>
      <update_rate>1.0</update_rate>
    </plugin>
    <include><uri>model://sun</uri></include>
    <model name="ground">
      <static>true</static>
      <pose>0 0 -0.25 0 0 0</pose>
      <link name="ground">
        <collision name="collision"><geometry><box><size>200 200 0.5</size></box></geometry>
          <surface><friction><ode><mu>{FRICTION}</mu><mu2>{FRICTION}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual"><geometry><box><size>200 200 0.5</size></box></geometry></visual>
      </link>
    </model>{ramps}
  </world>
</sdf>
'''


def along_slope(angle_deg, x, z):
    """Distance up the ramp of base_root at (x, z); negative on the flat before the foot.

    The body sits BODY_HEIGHT along the surface normal, which is perpendicular to
    the ramp direction, so projecting onto (cos t, sin t) removes it.
    """
    if x <= FOOT_X:
        return x - FOOT_X
    t = math.radians(angle_deg)
    return (x - FOOT_X) * math.cos(t) + z * math.sin(t)


def up_z(q):
    """World z component of the body's up axis (1 upright, 0 on its side)."""
    w, x, y, z = q
    return 1 - 2 * (x * x + y * y)


def yaw_of(q):
    w, x, y, z = q
    return math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write-world', metavar='PATH', help='write the ramp world and exit')
    parser.add_argument('--angles', type=float, nargs='+', default=DEFAULT_ANGLES)
    parser.add_argument('--tests', nargs='+', default=['climb', 'descend', 'park', 'across', 'turn'])
    parser.add_argument('--output', help='write results as JSON')
    args = parser.parse_args(argv)
    angles = [a if a != int(a) else int(a) for a in args.angles]
    if args.write_world:
        with open(args.write_world, 'w') as f:
            f.write(world_sdf(angles))
        print(f'wrote {args.write_world}: ramps at {angles} deg')
        return 0
    results = run_tests(angles, args.tests)
    print(json.dumps(results, indent=2))
    if args.output:
        with open(args.output, 'w') as f:
            json.dump(results, f, indent=2)
    return 0


def run_tests(angles, tests):
    import rclpy
    from gazebo_msgs.msg import EntityState
    from gazebo_msgs.srv import SetEntityState
    from geometry_msgs.msg import Twist
    from nav_msgs.msg import Odometry

    rclpy.init()
    node = rclpy.create_node('slope_test')
    state = {}

    def on_odom(msg):
        p, o = msg.pose.pose.position, msg.pose.pose.orientation
        state['pose'] = ((p.x, p.y, p.z), (o.w, o.x, o.y, o.z))
        state['stamp'] = msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9

    node.create_subscription(Odometry, '/ground_truth/odom', on_odom, 10)
    cmd = node.create_publisher(Twist, '/cmd_vel', 10)
    teleport = node.create_client(SetEntityState, '/gazebo/set_entity_state')
    if not teleport.wait_for_service(timeout_sec=30):
        sys.exit('no /gazebo/set_entity_state: start the sim with the slope test world')

    def spin_for(sim_seconds, twist=None, sample=None):
        """Spin for a span of simulation time, publishing twist at 10 Hz."""
        while 'stamp' not in state:
            rclpy.spin_once(node, timeout_sec=0.1)
        start = state['stamp']
        next_cmd = 0.0
        wall_limit = time.monotonic() + sim_seconds * 20 + 30
        while state['stamp'] - start < sim_seconds:
            if time.monotonic() > wall_limit:
                raise RuntimeError('simulation is not advancing (paused?)')
            if twist is not None and time.monotonic() >= next_cmd:
                cmd.publish(twist)
                next_cmd = time.monotonic() + 0.1
            rclpy.spin_once(node, timeout_sec=0.02)
            if sample:
                if sample(state['pose']):
                    break
        if twist is not None:
            cmd.publish(Twist())

    def place(position, quat):
        request = SetEntityState.Request()
        request.state = EntityState(name='proxy_rover', reference_frame='world')
        p = request.state.pose.position
        p.x, p.y, p.z = position[0], position[1], position[2] + 0.01
        o = request.state.pose.orientation
        o.w, o.x, o.y, o.z = quat
        future = teleport.call_async(request)
        rclpy.spin_until_future_complete(node, future, timeout_sec=10)
        if not future.result() or not future.result().success:
            raise RuntimeError('set_entity_state failed')
        state.pop('stamp', None)
        spin_for(2.0)          # settle on the wheels with no command

    def twist(linear=0.0, angular=0.0):
        t = Twist()
        t.linear.x, t.angular.z = linear, angular
        return t

    def s_of(angle, pose):
        return along_slope(angle, pose[0][0], pose[0][2])

    results = []
    for index, angle in enumerate(angles):
        row = ramp_row_y(index)
        result = {'angle_deg': angle}
        worst_up = [1.0]

        def watch(pose):
            worst_up[0] = min(worst_up[0], up_z(pose[1]))
            return worst_up[0] < 0.2          # tipped over: stop the test

        if 'climb' in tests:
            worst_up[0] = 1.0
            place(*slope_pose(angle, row, -1.5))
            t0, s0 = state['stamp'], s_of(angle, state['pose'])
            trace = []

            def climb_watch(pose):
                trace.append((state['stamp'], s_of(angle, pose)))
                return watch(pose) or s_of(angle, pose) >= 5.0

            spin_for(40.0, twist(SPEED), climb_watch)
            s_end = s_of(angle, state['pose'])
            on_ramp = [(t, s) for t, s in trace if 0.5 <= s <= 4.5]
            speed = ((on_ramp[-1][1] - on_ramp[0][1]) / (on_ramp[-1][0] - on_ramp[0][0])
                     if len(on_ramp) > 2 and on_ramp[-1][0] > on_ramp[0][0] else 0.0)
            result['climb'] = {'reached_m': round(s_end, 3), 'ok': s_end >= 5.0 and worst_up[0] > 0.5,
                               'speed_on_ramp': round(speed, 3), 'slip': round(1 - speed / SPEED, 3),
                               'time_s': round(state['stamp'] - t0, 2), 'start_m': round(s0, 2),
                               'min_up_z': round(worst_up[0], 3)}

        if 'descend' in tests:
            worst_up[0] = 1.0
            place(*slope_pose(angle, row, 6.5, yaw=math.pi))
            s0, t0 = s_of(angle, state['pose']), state['stamp']
            spin_for(3.0, twist(SPEED), watch)
            s1, t1 = s_of(angle, state['pose']), state['stamp']
            spin_for(3.0, None, watch)
            s2 = s_of(angle, state['pose'])
            result['descend'] = {'speed': round((s0 - s1) / max(t1 - t0, 1e-6), 3),
                                 'slide_after_stop_m': round(s1 - s2, 3),
                                 'ok': s1 - s2 < 0.3 and worst_up[0] > 0.5 and (s0 - s1) < 3 * SPEED * 1.3,
                                 'min_up_z': round(worst_up[0], 3)}

        if 'park' in tests:
            # No command: rover_sim's wheel brake at zero speed is proportional only,
            # so on a slope the rover creeps downhill. Recorded, not pass/fail.
            worst_up[0] = 1.0
            place(*slope_pose(angle, row, 3.0))
            s0, t0 = s_of(angle, state['pose']), state['stamp']
            spin_for(5.0, None, watch)
            slide = s0 - s_of(angle, state['pose'])
            result['park'] = {'slide_5s_m': round(slide, 3),
                              'creep_m_per_s': round(slide / max(state['stamp'] - t0, 1e-6), 3),
                              'tipped': worst_up[0] <= 0.5}

        if 'across' in tests:
            for side, yaw in (('left_uphill', math.pi / 2), ('right_uphill', -math.pi / 2)):
                worst_up[0] = 1.0
                lateral = -2.0 if yaw > 0 else 2.0
                place(*slope_pose(angle, row, 3.0, lateral=lateral, yaw=yaw))
                s0, y0 = s_of(angle, state['pose']), state['pose'][0][1]
                spin_for(8.0, twist(SPEED), watch)
                drift = s0 - s_of(angle, state['pose'])
                travelled = abs(state['pose'][0][1] - y0)
                result['across_' + side] = {'travelled_m': round(travelled, 3),
                                            'downhill_drift_m': round(drift, 3),
                                            'ok': drift < 0.3 and travelled > 2.5 and worst_up[0] > 0.5,
                                            'min_up_z': round(worst_up[0], 3)}

        if 'turn' in tests:
            worst_up[0] = 1.0
            place(*slope_pose(angle, row, 3.0))
            s0 = s_of(angle, state['pose'])
            turned = [0.0, yaw_of(state['pose'][1])]

            def turn_watch(pose):
                yaw = yaw_of(pose[1])
                turned[0] += math.atan2(math.sin(yaw - turned[1]), math.cos(yaw - turned[1]))
                turned[1] = yaw
                return watch(pose) or abs(turned[0]) >= 2 * math.pi

            spin_for(30.0, twist(0.0, TURN_RATE), turn_watch)
            drift = s0 - s_of(angle, state['pose'])
            result['turn'] = {'turned_deg': round(math.degrees(turned[0]), 1), 'downhill_drift_m': round(drift, 3),
                              'ok': abs(turned[0]) >= 2 * math.pi * 0.95 and drift < 0.3 and worst_up[0] > 0.5,
                              'min_up_z': round(worst_up[0], 3)}

        result['ok'] = all(v['ok'] for v in result.values() if isinstance(v, dict) and 'ok' in v)
        print(json.dumps(result), flush=True)
        results.append(result)

    cmd.publish(Twist())
    node.destroy_node()
    rclpy.shutdown()
    return {'friction_mu': FRICTION, 'speed': SPEED, 'turn_rate': TURN_RATE, 'results': results}


if __name__ == '__main__':
    sys.exit(main())
