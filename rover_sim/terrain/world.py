"""SDF world composition for the Mars terrain and the deterministic test worlds.

World files are complete and standalone. Meshes, textures and the DEM are
referenced through ``model://mars_terrain/...`` so a world works from any
directory once ``GAZEBO_MODEL_PATH`` contains the generated ``models``
directory (the launch file sets it). The launch file overrides gravity and
shadows by substituting the ``<gravity>`` and ``<shadows>`` elements.
"""
import math
import re

MARS_GRAVITY = 3.71
MODEL_URI = 'model://mars_terrain'

PHYSICS = '''    <physics name="default_physics" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_update_rate>1000</real_time_update_rate>
      <real_time_factor>1</real_time_factor>
      <ode>
        <solver><type>quick</type><iters>60</iters><sor>1.3</sor></solver>
        <constraints><cfm>1e-5</cfm><erp>0.2</erp>
          <contact_max_correcting_vel>100</contact_max_correcting_vel>
          <contact_surface_layer>0.001</contact_surface_layer></constraints>
      </ode>
    </physics>
    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so">
      <ros><namespace>/gazebo</namespace></ros><update_rate>50</update_rate>
    </plugin>
'''

MARS_SCENE = '''    <scene>
      <ambient>0.42 0.34 0.28 1</ambient>
      <background>0.80 0.60 0.44 1</background>
      <shadows>@SHADOWS@</shadows>
      <fog><type>linear</type><color>0.80 0.61 0.46 1</color><start>40</start><end>260</end><density>1</density></fog>
      <grid>false</grid>
      <origin_visual>false</origin_visual>
    </scene>
    <light name="sun" type="directional">
      <cast_shadows>@SHADOWS@</cast_shadows>
      <pose>0 0 60 0 0 0</pose>
      <diffuse>0.95 0.80 0.64 1</diffuse>
      <specular>0.08 0.07 0.06 1</specular>
      <attenuation><range>1000</range><constant>0.9</constant><linear>0.01</linear><quadratic>0.001</quadratic></attenuation>
      <direction>-0.62 0.45 -0.55</direction>
    </light>
'''

FLAT_SCENE = '''    <scene>
      <ambient>0.5 0.45 0.4 1</ambient>
      <background>0.80 0.60 0.44 1</background>
      <shadows>@SHADOWS@</shadows>
      <grid>false</grid>
    </scene>
    <light name="sun" type="directional">
      <cast_shadows>@SHADOWS@</cast_shadows>
      <pose>0 0 30 0 0 0</pose>
      <diffuse>0.95 0.85 0.75 1</diffuse>
      <specular>0.1 0.1 0.1 1</specular>
      <direction>-0.5 0.3 -0.8</direction>
    </light>
'''


def friction(mu=0.65):
    return (f'<surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction>'
            '<contact><ode><kp>1e6</kp><kd>1e2</kd><min_depth>0.001</min_depth><max_vel>1.0</max_vel></ode></contact></surface>')


def terrain_model(pad_level, texture_blend, sampling=2, mu=0.65):
    low, high = texture_blend
    return f'''    <model name="mars_terrain">
      <static>true</static>
      <link name="terrain">
        <collision name="collision">
          <geometry><heightmap><uri>{MODEL_URI}/heightmap.tif</uri><pos>0 0 0</pos><sampling>{sampling}</sampling></heightmap></geometry>
          {friction(mu)}
        </collision>
        <visual name="visual">
          <geometry><heightmap>
            <uri>{MODEL_URI}/heightmap.tif</uri><pos>0 0 0</pos><sampling>{sampling}</sampling>
            <texture><diffuse>{MODEL_URI}/textures/sand_albedo.png</diffuse><normal>{MODEL_URI}/textures/sand_normal.png</normal><size>6</size></texture>
            <texture><diffuse>{MODEL_URI}/textures/gravel_albedo.png</diffuse><normal>{MODEL_URI}/textures/gravel_normal.png</normal><size>4</size></texture>
            <texture><diffuse>{MODEL_URI}/textures/basalt_albedo.png</diffuse><normal>{MODEL_URI}/textures/basalt_normal.png</normal><size>5</size></texture>
            <blend><min_height>{low:.2f}</min_height><fade_dist>2.5</fade_dist></blend>
            <blend><min_height>{high:.2f}</min_height><fade_dist>3.0</fade_dist></blend>
          </heightmap></geometry>
        </visual>
      </link>
    </model>
'''


def mars_world(name, pad_level, texture_blend, rocks_sdf, boulders_sdf, gravity=MARS_GRAVITY,
               shadows=False, sampling=2, camera_pose='-14 -14 12 0 0.45 0.78'):
    body = (f'<?xml version="1.0"?>\n<!-- Generated by rover_sim/scripts/generate_terrain.py; do not edit. -->\n'
            f'<sdf version="1.6">\n  <world name="{name}">\n'
            f'    <gravity>0 0 {-gravity}</gravity>\n' + PHYSICS + MARS_SCENE +
            f'    <gui fullscreen="0"><camera name="overview"><pose>{camera_pose}</pose>'
            '<view_controller>orbit</view_controller></camera></gui>\n' +
            terrain_model(pad_level, texture_blend, sampling) + rocks_sdf + '\n' + boulders_sdf + '\n'
            '  </world>\n</sdf>\n')
    return body.replace('@SHADOWS@', 'true' if shadows else 'false')


def ground_plane(size=80.0, mu=0.65, colour='0.76 0.56 0.38'):
    return f'''    <model name="ground"><static>true</static><pose>0 0 -0.25 0 0 0</pose><link name="ground">
      <collision name="collision"><geometry><box><size>{size} {size} 0.5</size></box></geometry>{friction(mu)}</collision>
      <visual name="visual"><geometry><box><size>{size} {size} 0.5</size></box></geometry>
        <material><ambient>{colour} 1</ambient><diffuse>{colour} 1</diffuse></material></visual>
    </link></model>
'''


def box_model(name, x, y, z, sx, sy, sz, roll=0.0, pitch=0.0, yaw=0.0, colour='0.45 0.42 0.40', mu=0.65):
    return (f'    <model name="{name}"><static>true</static><pose>{x:.4f} {y:.4f} {z:.4f} {roll:.5f} {pitch:.5f} {yaw:.5f}</pose>'
            f'<link name="link"><collision name="collision"><geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>{friction(mu)}</collision>'
            f'<visual name="visual"><geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>'
            f'<material><ambient>{colour} 1</ambient><diffuse>{colour} 1</diffuse></material></visual></link></model>\n')


def flat_world(name, models, gravity=MARS_GRAVITY, shadows=False, camera_pose='-6 -10 6 0 0.4 1.0', size=80.0):
    body = (f'<?xml version="1.0"?>\n<!-- Generated by rover_sim/scripts/generate_terrain.py --test-worlds; do not edit. -->\n'
            f'<sdf version="1.6">\n  <world name="{name}">\n'
            f'    <gravity>0 0 {-gravity}</gravity>\n' + PHYSICS + FLAT_SCENE +
            f'    <gui fullscreen="0"><camera name="overview"><pose>{camera_pose}</pose>'
            '<view_controller>orbit</view_controller></camera></gui>\n' + ground_plane(size) +
            ''.join(models) + '  </world>\n</sdf>\n')
    return body.replace('@SHADOWS@', 'true' if shadows else 'false')


STEP_HEIGHTS = (0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.40)
RAMP_ANGLES = (5, 10, 15, 20, 25, 30, 35, 40)
LANE_SPACING = 4.0
STEP_X_START, STEP_LENGTH, STEP_WIDTH = 3.0, 4.0, 3.0
RAMP_RUNUP, RAMP_LENGTH, RAMP_WIDTH, RAMP_TOP = 3.0, 8.0, 3.0, 4.0


def step_lanes():
    """(height, lane_y) for every step trial; the rover starts at x=0 on the lane."""
    n = len(STEP_HEIGHTS)
    return [(h, (i - (n - 1) / 2) * LANE_SPACING) for i, h in enumerate(STEP_HEIGHTS)]


def ramp_lanes():
    n = len(RAMP_ANGLES)
    return [(a, (i - (n - 1) / 2) * LANE_SPACING) for i, a in enumerate(RAMP_ANGLES)]


def step_test_world(gravity=MARS_GRAVITY):
    models = []
    for h, y in step_lanes():
        models.append(box_model(f'step_{int(round(h * 100)):02d}cm', STEP_X_START + STEP_LENGTH / 2, y, h / 2,
                                STEP_LENGTH, STEP_WIDTH, h, colour='0.5 0.47 0.44'))
    return flat_world('step_test', models, gravity, camera_pose='-8 -22 10 0 0.5 0.9')


def ramp_geometry(angle_deg):
    """Return (ramp box pose/size, top box pose/size) for a ramp lane.

    The ramp's upper face starts at ground level at x = RAMP_RUNUP and rises
    along +x for RAMP_LENGTH metres of horizontal run.
    """
    theta = math.radians(angle_deg)
    thickness = 0.5
    run = RAMP_LENGTH
    length = run / math.cos(theta)
    # Top face from (RAMP_RUNUP, 0) to (RAMP_RUNUP + run, run*tan). Box centre is
    # half a thickness below the face centre along the face normal.
    fx, fz = RAMP_RUNUP + run / 2, run * math.tan(theta) / 2
    cx = fx + (thickness / 2) * math.sin(theta)
    cz = fz - (thickness / 2) * math.cos(theta)
    top_height = run * math.tan(theta)
    top = (RAMP_RUNUP + run + RAMP_TOP / 2 + 0.3, top_height - thickness / 2, RAMP_TOP + 0.6, RAMP_WIDTH, thickness)
    return (cx, cz, length, RAMP_WIDTH, thickness, theta), top, top_height


def slope_test_world(gravity=MARS_GRAVITY):
    models = []
    for angle, y in ramp_lanes():
        (cx, cz, length, width, thickness, theta), (tx, tz, tl, tw, tt), _ = ramp_geometry(angle)
        models.append(box_model(f'ramp_{angle:02d}deg', cx, y, cz, length, width, thickness,
                                pitch=-theta, colour='0.52 0.45 0.40'))
        models.append(box_model(f'ramp_{angle:02d}deg_top', tx, y, tz, tl, tw, tt, colour='0.45 0.42 0.40'))
    return flat_world('slope_test', models, gravity, camera_pose='-10 -26 14 0 0.55 0.9', size=100.0)


def boulder_garden_world(boulders_sdf, gravity=MARS_GRAVITY):
    return flat_world('boulder_garden', [boulders_sdf + '\n'], gravity, camera_pose='4 -14 8 0 0.5 1.3')


def override_world(text, gravity=None, shadows=None):
    """Substitute gravity and shadow settings in a generated world."""
    if gravity is not None:
        text = re.sub(r'<gravity>[^<]*</gravity>', f'<gravity>0 0 {-float(gravity)}</gravity>', text, count=1)
    if shadows is not None:
        flag = 'true' if shadows else 'false'
        text = re.sub(r'<shadows>[^<]*</shadows>', f'<shadows>{flag}</shadows>', text)
        text = re.sub(r'<cast_shadows>[^<]*</cast_shadows>', f'<cast_shadows>{flag}</cast_shadows>', text)
    return text
